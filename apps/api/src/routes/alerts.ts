import type { Alert } from "@repo/db";
import type { FastifyPluginAsyncZod } from "fastify-type-provider-zod";
import { z } from "zod";
import { tenantOf } from "../http/access.ts";
import { notFound } from "../http/errors.ts";
import { requirePersonAccess } from "../http/person-gate.ts";
import {
  IdParams,
  iso,
  isoOrNull,
  LIMIT_MAX,
  optionalInstant,
  page,
  PROTECTED_ERRORS,
  SECURITY,
} from "./schemas.ts";

export const AlertView = z.object({
  id: z.uuid(),
  monitorId: z.uuid(),
  title: z.string(),
  evidenceId: z.uuid().nullable(),
  createdAt: z.iso.datetime(),
  acknowledgedAt: optionalInstant,
  acknowledgedByUserId: z.uuid().nullable(),
});

export type AlertViewType = z.infer<typeof AlertView>;

export const viewAlert = (row: Alert): AlertViewType => ({
  id: row.id,
  monitorId: row.monitorId,
  title: row.title,
  evidenceId: row.evidenceId,
  createdAt: iso(row.createdAt),
  acknowledgedAt: isoOrNull(row.acknowledgedAt),
  acknowledgedByUserId: row.acknowledgedByUserId,
});

/** The collected evidence an alert links to; an alert with no link contributes none. */
function evidenceIdsOf(rows: readonly Alert[]): string[] {
  return rows.map((row) => row.evidenceId).filter((id): id is string => id !== null);
}

/** What a locked alert read withholds, named in the Locked refusal. */
const ALERT_WITHHELD = "The alert and the collected evidence it was raised from.";

const AlertListQuery = z.object({
  limit: z.coerce.number().int().min(1).max(LIMIT_MAX).default(50),
  monitorId: z.uuid().optional(),
  acknowledged: z
    .union([z.boolean(), z.enum(["true", "false"])])
    .transform((v) => (typeof v === "boolean" ? v : v === "true"))
    .optional(),
});

export const alertRoutes: FastifyPluginAsyncZod = (app) => {
  app.get(
    "/api/v1/alerts",
    {
      config: { access: { permission: "alert:read", action: "alert.list", snapshot: true } },
      schema: {
        operationId: "listAlerts",
        summary:
          "List alerts generated by monitors, filterable by monitor or acknowledgement state",
        tags: ["alerts"],
        security: SECURITY,
        querystring: AlertListQuery,
        response: {
          200: z.object({ items: z.array(AlertView), hasMore: z.boolean() }),
          ...PROTECTED_ERRORS,
        },
      },
    },
    async (request) => {
      const context = tenantOf(request);
      const { repos } = context;
      const { limit, monitorId, acknowledged } = request.query;

      const rows = await repos.alerts.list({
        limit: limit + 1,
        monitorId,
        acknowledged,
      });

      const result = page(rows, limit);
      // An alert links to collected evidence that can rest on person data; refuse
      // the whole list when the tenant may not access it (CLAUDE.md §9: never thinned).
      await requirePersonAccess(
        context,
        { evidenceIds: evidenceIdsOf(result.items) },
        ALERT_WITHHELD,
      );
      return { items: result.items.map(viewAlert), hasMore: result.hasMore };
    },
  );

  app.get(
    "/api/v1/alerts/:id",
    {
      config: { access: { permission: "alert:read", action: "alert.read", snapshot: true } },
      schema: {
        operationId: "getAlert",
        summary: "Inspect an alert by ID, including evidence link if correlated",
        tags: ["alerts"],
        security: SECURITY,
        params: IdParams,
        response: { 200: AlertView, ...PROTECTED_ERRORS },
      },
    },
    async (request) => {
      const context = tenantOf(request);
      const { repos } = context;
      const row = await repos.alerts.findById(request.params.id);
      if (row === null) throw notFound("The alert");
      await requirePersonAccess(context, { evidenceIds: evidenceIdsOf([row]) }, ALERT_WITHHELD);
      return viewAlert(row);
    },
  );

  app.post(
    "/api/v1/alerts/:id/ack",
    {
      config: { access: { permission: "alert:write", action: "alert.acknowledge" } },
      schema: {
        operationId: "acknowledgeAlert",
        summary: "Acknowledge an alert as reviewed by the analyst",
        tags: ["alerts"],
        security: SECURITY,
        params: IdParams,
        response: { 200: AlertView, ...PROTECTED_ERRORS },
      },
    },
    async (request) => {
      const context = tenantOf(request);
      const { repos, principal } = context;
      const userId = principal.kind === "session" ? principal.userId : principal.issuerUserId;

      if (!userId) {
        throw notFound("User identity for alert acknowledgement");
      }

      const existing = await repos.alerts.findById(request.params.id);
      if (existing === null) throw notFound("The alert");
      await requirePersonAccess(
        context,
        { evidenceIds: evidenceIdsOf([existing]) },
        ALERT_WITHHELD,
      );

      if (existing.acknowledgedAt !== null) {
        // Already acknowledged: idempotent return
        return viewAlert(existing);
      }

      const updated = await repos.alerts.acknowledge(request.params.id, userId);
      if (updated === null) throw notFound("The alert");

      request.auditTarget = { type: "alert", id: updated.id };
      return viewAlert(updated);
    },
  );

  return Promise.resolve();
};
