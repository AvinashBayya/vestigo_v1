/**
 * Generates the API client in src/client from the OpenAPI document the API
 * emits at build time. Everything in src/client is generated: it is
 * gitignored, never hand-edited, and rebuilt by the turbo `generate` task.
 *
 *   schema.gen.ts  every path, parameter and response type in the spec
 *   index.ts       the client, typed by those paths: a call to a path or with a
 *                  shape the spec does not describe fails to compile
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

// Resolved through @repo/api's package exports, not a relative path into it.
const spec = createRequire(import.meta.url).resolve("@repo/api/openapi.json");
const outDir = new URL("../src/client/", import.meta.url);
const banner = "// Generated by apps/web/scripts/generate-client.ts. Do not edit.\n";

const schema = astToString(await openapiTS(pathToFileURL(spec)));

mkdirSync(outDir, { recursive: true });
writeFileSync(new URL("schema.gen.ts", outDir), banner + schema);
writeFileSync(
  new URL("index.ts", outDir),
  `${banner}import createClient from "openapi-fetch";
import type { paths } from "./schema.gen.ts";

export type { paths };

/** Same-origin: in development Vite proxies API paths to the API server. */
export const api = createClient<paths>({ baseUrl: globalThis.location.origin });
`,
);
console.log(`Generated API client from ${spec}`);
