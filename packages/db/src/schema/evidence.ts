import { sql } from "drizzle-orm";
import {
  check,
  foreignKey,
  index,
  jsonb,
  pgTable,
  primaryKey,
  text,
  timestamp,
  uuid,
} from "drizzle-orm/pg-core";
import { collectorsRegistry } from "./collectors.ts";
import { createdAtColumn, idColumn, optionalTimestamp, tenantIdColumn } from "./columns.ts";
import { entities, entityRelationships } from "./entities.ts";
import { claimStrength } from "./enums.ts";
import { tenants } from "./tenancy.ts";
import { jobs } from "./work.ts";

/**
 * Append-only evidence. The application role may only SELECT and INSERT, and a
 * trigger rejects UPDATE from every role.
 *
 * Partitioned by month on `id`: ids are UUIDv7, generated by the database, so
 * their leading 48 bits are the insert time and each month is one id range.
 * (The migration adds `PARTITION BY RANGE (id)`; Drizzle cannot express it.)
 * `created_at` is computed from the id, so it always agrees with the partition.
 *
 * Timestamps: observed_at is when the source says the thing happened;
 * collected_at is when a collector fetched it. Both are nullable and have no
 * default. Null means "not known"; neither is ever filled from the other or
 * from the clock.
 */
export const evidence = pgTable(
  "evidence",
  {
    tenantId: tenantIdColumn(),
    id: uuid("id")
      .notNull()
      .default(sql`app.uuid_generate_v7()`),
    collectorId: text("collector_id").notNull(),
    collectorVersion: text("collector_version").notNull(),
    jobId: uuid("job_id"),
    sourceUrl: text("source_url"),
    /** sha256 of the raw payload, as `sha256:<64 hex>`. */
    contentHash: text("content_hash").notNull(),
    /** Key of the raw payload in the content-addressed store. */
    payloadRef: text("payload_ref").notNull(),
    observedAt: optionalTimestamp("observed_at"),
    collectedAt: optionalTimestamp("collected_at"),
    claimStrength: claimStrength("claim_strength").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .generatedAlwaysAs(sql`app.uuid_v7_timestamp(id)`),
  },
  (t) => [
    primaryKey({ name: "evidence_pk", columns: [t.tenantId, t.id] }),
    foreignKey({
      name: "evidence_tenant_fk",
      columns: [t.tenantId],
      foreignColumns: [tenants.tenantId],
    }),
    foreignKey({
      name: "evidence_collector_fk",
      columns: [t.tenantId, t.collectorId],
      foreignColumns: [collectorsRegistry.tenantId, collectorsRegistry.collectorId],
    }),
    foreignKey({
      name: "evidence_job_fk",
      columns: [t.tenantId, t.jobId],
      foreignColumns: [jobs.tenantId, jobs.id],
    }),
    index("evidence_content_hash_idx").on(t.tenantId, t.contentHash),
    check("evidence_id_is_uuid_v7", sql`substr(${t.id}::text, 15, 1) = '7'`),
    check("evidence_content_hash_format", sql`${t.contentHash} ~ '^sha256:[0-9a-f]{64}$'`),
    check("evidence_payload_ref_not_blank", sql`length(btrim(${t.payloadRef})) > 0`),
    check("evidence_collector_version_not_blank", sql`length(btrim(${t.collectorVersion})) > 0`),
    check(
      "evidence_source_url_scheme",
      sql`${t.sourceUrl} is null or ${t.sourceUrl} ~ '^https?://'`,
    ),
  ],
);

/**
 * A statement about an entity or a relationship, carrying its strength and
 * citing the evidence it rests on. Append-only for the application role.
 */
export const claims = pgTable(
  "claims",
  {
    tenantId: tenantIdColumn(),
    id: idColumn(),
    evidenceId: uuid("evidence_id").notNull(),
    entityId: uuid("entity_id"),
    relationshipId: uuid("relationship_id"),
    attribute: text("attribute").notNull(),
    value: jsonb("value"),
    strength: claimStrength("strength").notNull(),
    createdAt: createdAtColumn(),
  },
  (t) => [
    primaryKey({ name: "claims_pk", columns: [t.tenantId, t.id] }),
    foreignKey({
      name: "claims_tenant_fk",
      columns: [t.tenantId],
      foreignColumns: [tenants.tenantId],
    }),
    foreignKey({
      name: "claims_evidence_fk",
      columns: [t.tenantId, t.evidenceId],
      foreignColumns: [evidence.tenantId, evidence.id],
    }),
    foreignKey({
      name: "claims_entity_fk",
      columns: [t.tenantId, t.entityId],
      foreignColumns: [entities.tenantId, entities.id],
    }),
    foreignKey({
      name: "claims_relationship_fk",
      columns: [t.tenantId, t.relationshipId],
      foreignColumns: [entityRelationships.tenantId, entityRelationships.id],
    }),
    index("claims_entity_idx").on(t.tenantId, t.entityId),
    index("claims_evidence_idx").on(t.tenantId, t.evidenceId),
    check("claims_one_subject", sql`num_nonnulls(${t.entityId}, ${t.relationshipId}) = 1`),
    check("claims_attribute_format", sql`${t.attribute} ~ '^[a-z][a-z0-9_]*$'`),
  ],
);
