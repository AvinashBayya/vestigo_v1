import { sql } from "drizzle-orm";
import {
  bigint,
  boolean,
  check,
  index,
  integer,
  pgSchema,
  text,
  timestamp,
  unique,
  uuid,
} from "drizzle-orm/pg-core";

/**
 * Identity, owned by the identity provider (Better Auth). These tables are the
 * one exception to "every table carries tenant_id" (CLAUDE.md §2): a person
 * signs in before any tenant is known, and one identity may belong to several
 * tenants. They hold identity and membership only, never investigation data,
 * and only the app_auth role can reach them; app_runtime has no privilege on
 * this schema, and app_auth has none on tenant data. The exempt set is fixed
 * by a schema test.
 *
 * Column keys are the provider's field names; column names are snake_case.
 * Ids are generated by the database (the provider's `generateId: "uuid"`).
 * An organization's id IS the tenant id (public.tenants.tenant_id).
 */
export const authSchema = pgSchema("auth");

const at = (name: string) => timestamp(name, { withTimezone: true });
const createdAt = () => at("created_at").notNull().defaultNow();
const updatedAt = () => at("updated_at").notNull().defaultNow();

export const authUser = authSchema.table(
  "user",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    name: text("name").notNull(),
    email: text("email").notNull().unique("user_email_key"),
    emailVerified: boolean("email_verified").notNull().default(false),
    image: text("image"),
    twoFactorEnabled: boolean("two_factor_enabled").notNull().default(false),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [check("user_email_normalised", sql`${t.email} = lower(${t.email})`)],
);

export const authOrganization = authSchema.table("organization", {
  id: uuid("id").primaryKey().defaultRandom(),
  name: text("name").notNull(),
  slug: text("slug").notNull().unique("organization_slug_key"),
  logo: text("logo"),
  metadata: text("metadata"),
  createdAt: createdAt(),
});

export const authSession = authSchema.table(
  "session",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    token: text("token").notNull().unique("session_token_key"),
    userId: uuid("user_id")
      .notNull()
      .references(() => authUser.id, { onDelete: "cascade" }),
    expiresAt: at("expires_at").notNull(),
    ipAddress: text("ip_address"),
    userAgent: text("user_agent"),
    activeOrganizationId: uuid("active_organization_id").references(() => authOrganization.id, {
      onDelete: "set null",
    }),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [index("session_user_idx").on(t.userId)],
);

export const authAccount = authSchema.table(
  "account",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    accountId: text("account_id").notNull(),
    providerId: text("provider_id").notNull(),
    userId: uuid("user_id")
      .notNull()
      .references(() => authUser.id, { onDelete: "cascade" }),
    accessToken: text("access_token"),
    refreshToken: text("refresh_token"),
    idToken: text("id_token"),
    accessTokenExpiresAt: at("access_token_expires_at"),
    refreshTokenExpiresAt: at("refresh_token_expires_at"),
    scope: text("scope"),
    /** A scrypt hash, written by the identity provider. Never a plaintext password. */
    password: text("password"),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [index("account_user_idx").on(t.userId)],
);

export const authVerification = authSchema.table(
  "verification",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    identifier: text("identifier").notNull(),
    value: text("value").notNull(),
    expiresAt: at("expires_at").notNull(),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [index("verification_identifier_idx").on(t.identifier)],
);

/** TOTP secret and backup codes, encrypted by the identity provider before storage. */
export const authTwoFactor = authSchema.table(
  "two_factor",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    secret: text("secret").notNull(),
    backupCodes: text("backup_codes").notNull(),
    userId: uuid("user_id")
      .notNull()
      .references(() => authUser.id, { onDelete: "cascade" }),
    verified: boolean("verified").notNull().default(true),
    failedVerificationCount: integer("failed_verification_count").notNull().default(0),
    lockedUntil: at("locked_until"),
  },
  (t) => [index("two_factor_user_idx").on(t.userId)],
);

/** Role names are the catalogue's; an unknown name is refused rather than granting nothing. */
const ROLE_LIST = "(owner|admin|analyst|viewer)";

export const authMember = authSchema.table(
  "member",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    organizationId: uuid("organization_id")
      .notNull()
      .references(() => authOrganization.id, { onDelete: "cascade" }),
    userId: uuid("user_id")
      .notNull()
      .references(() => authUser.id, { onDelete: "cascade" }),
    role: text("role").notNull(),
    createdAt: createdAt(),
  },
  (t) => [
    unique("member_organization_user_key").on(t.organizationId, t.userId),
    index("member_user_idx").on(t.userId),
    check("member_role_known", sql`${t.role} ~ ${sql.raw(`'^${ROLE_LIST}(,${ROLE_LIST})*$'`)}`),
  ],
);

export const authInvitation = authSchema.table(
  "invitation",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    organizationId: uuid("organization_id")
      .notNull()
      .references(() => authOrganization.id, { onDelete: "cascade" }),
    email: text("email").notNull(),
    role: text("role").notNull(),
    status: text("status").notNull().default("pending"),
    expiresAt: at("expires_at").notNull(),
    inviterId: uuid("inviter_id")
      .notNull()
      .references(() => authUser.id, { onDelete: "cascade" }),
    createdAt: createdAt(),
  },
  (t) => [
    index("invitation_organization_idx").on(t.organizationId),
    index("invitation_email_idx").on(t.email),
    check(
      "invitation_status_known",
      sql`${t.status} in ('pending', 'accepted', 'rejected', 'canceled')`,
    ),
    check("invitation_role_known", sql`${t.role} ~ ${sql.raw(`'^${ROLE_LIST}(,${ROLE_LIST})*$'`)}`),
  ],
);

/** The identity provider's rate-limit counters, shared by every API replica. */
export const authRateLimit = authSchema.table("rate_limit", {
  id: uuid("id").primaryKey().defaultRandom(),
  key: text("key").notNull().unique("rate_limit_key_key"),
  count: integer("count").notNull(),
  lastRequest: bigint("last_request", { mode: "number" }).notNull(),
});

/** Keyed by the provider's model names, as its adapter expects. */
export const authTables = {
  user: authUser,
  session: authSession,
  account: authAccount,
  verification: authVerification,
  twoFactor: authTwoFactor,
  organization: authOrganization,
  member: authMember,
  invitation: authInvitation,
  rateLimit: authRateLimit,
} as const;

